# ENTRADA
nota = int(input("Digite a sua nota de 0 a 9: "))

# PROCESSAMENTO
# Não há cálculos necessários antes da verificação.

# SAÍDA
if nota == 0:
    print("Sua nota foi: zero")
elif nota == 1:
    print("Sua nota foi: um")
elif nota == 2:
    print("Sua nota foi: dois")
elif nota == 3:
    print("Sua nota foi: três")
elif nota == 4:
    print("Sua nota foi: quatro")
elif nota == 5:
    print("Sua nota foi: cinco")
elif nota == 6:
    print("Sua nota foi: seis")
elif nota == 7:
    print("Sua nota foi: sete")
elif nota == 8:
    print("Sua nota foi: oito")
elif nota == 9:
    print("Sua nota foi: nove")
else:
    print("Nota inválida! Digite apenas números entre 0 e 9.")